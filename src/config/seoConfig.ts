// Dynamic page SEO helper
export const getPageSEO = (page: keyof (typeof SEO_CONFIG)["pages"]) => {
  return SEO_CONFIG.pages[page] || SEO_CONFIG.pages.home;
};

// Generate full SEO config for a page with canonical URL
export const generatePageSEO = (
  page: keyof (typeof SEO_CONFIG)["pages"],
  custom?: any,
) => {
  const baseSEO = getPageSEO(page);
  const pageUrl = page === "home" ? "/" : `/${page}`;

  return {
    ...baseSEO,
    url: `${SEO_CONFIG.site.url}${pageUrl}`,
    canonical: `${SEO_CONFIG.site.url}${pageUrl}`,
    ogImage: SEO_CONFIG.site.image,
    ogType: "business.business",
    ...custom,
  };
};

// Get breadcrumb schema for structured data
export const getBreadcrumbSchema = (
  page: keyof (typeof SEO_CONFIG)["breadcrumbs"],
) => {
  const breadcrumbs =
    SEO_CONFIG.breadcrumbs[page] || SEO_CONFIG.breadcrumbs.home;

  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: breadcrumbs.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: `${SEO_CONFIG.site.url}${item.url}`,
    })),
  };
};

